class doctemplate_images_form extends \moodleform {
    /**
     * Defines the form fields.
     */
    public function definition() {
        $mform = $this->_form;

        $mform->addElement('hidden', 'id');
        $mform->setType('id', PARAM_INT);
        $mform->addElement(
            'filemanager',
            'docimages',
            get_string('doctplimages', 'mod_these'),
            null,
            $this->_customdata['options']
        );
        $mform->addHelpButton('docimages', 'doctplimages', 'mod_these');
        $this->add_action_buttons(false, get_string('savechanges'));
    }
}
